// Regenerates src/data/<language>.ts from the Unicode emoji list and CLDR's localized emoji names.
// To update, bump the versions below and run `npm run generate:emoji`.
import fs from 'fs';
import path from 'path';
import prettier from 'prettier';

const EMOJI_VERSION = '18.0.0';
const CLDR_VERSION = '49.0.0';

const EMOJI_TEST_URL = `https://unicode.org/Public/${EMOJI_VERSION}/emoji/emoji-test.txt`;
const CLDR_URL = 'https://cdn.jsdelivr.net/npm';

const dataDir = path.join(process.cwd(), 'src', 'data');
const languages = fs
  .readdirSync(dataDir)
  .filter((file) => file.endsWith('.ts') && file !== 'loader.ts')
  .map((file) => path.basename(file, '.ts'));

const fetchText = async (url) => {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }
  return response.text();
};

// Fully-qualified emojis plus skin tone/hair components, in Unicode's order
const parseEmojiTest = (text) =>
  text
    .split('\n')
    .map((line) => line.match(/^([0-9A-F ]+?)\s*;\s*(fully-qualified|component)\s*#/))
    .filter(Boolean)
    .map((match) => String.fromCodePoint(...match[1].split(' ').map((hex) => parseInt(hex, 16))));

// Users type regular spaces, but some CLDR names contain (narrow) no-break spaces
const normalizeName = (name) => name?.replace(/[\u00A0\u202F]/g, ' ').normalize('NFC');

// CLDR keys its annotations without the U+FE0F variation selector
const loadNames = async (language) => {
  const [base, derived] = await Promise.all([
    fetchText(`${CLDR_URL}/cldr-annotations-full@${CLDR_VERSION}/annotations/${language}/annotations.json`),
    fetchText(
      `${CLDR_URL}/cldr-annotations-derived-full@${CLDR_VERSION}/annotationsDerived/${language}/annotations.json`
    ),
  ]);
  const annotations = {
    ...JSON.parse(derived).annotationsDerived.annotations,
    ...JSON.parse(base).annotations.annotations,
  };
  return (emoji) => normalizeName(annotations[emoji.replace(/\uFE0F/g, '')]?.tts?.[0]);
};

const emojis = parseEmojiTest(await fetchText(EMOJI_TEST_URL));
const prettierConfig = await prettier.resolveConfig(dataDir);

for (const language of languages) {
  const nameOf = await loadNames(language);
  const entries = emojis.map((emoji) => [emoji, nameOf(emoji)]);
  const missing = entries.filter(([, name]) => !name).map(([emoji]) => emoji);
  const lines = entries
    .filter(([, name]) => name)
    .map(([emoji, name]) => `  ${JSON.stringify(emoji)}: ${JSON.stringify(name)},`);

  const source = [
    `// Generated by generate-emoji-data.mjs from Unicode Emoji ${EMOJI_VERSION} and CLDR ${CLDR_VERSION}. Do not edit.`,
    // An explicit type keeps the emitted .d.ts from listing every emoji as a property
    'const emojis: Record<string, string> = {',
    ...lines,
    '};',
    '',
    'export default emojis;',
    '',
  ].join('\n');
  const filePath = path.join(dataDir, `${language}.ts`);
  fs.writeFileSync(filePath, await prettier.format(source, { ...prettierConfig, filepath: filePath }), 'utf-8');

  console.log(
    `${language}: ${lines.length} emojis${missing.length ? `, ${missing.length} without a CLDR name: ${missing.join(' ')}` : ''}`
  );
}
